package com.example.resumemanager.model;

import java.time.LocalDateTime;

public class ChatBot {
    private Long id;
    private String name;
    private String wechatId;
    private String avatarUrl;
    private String status;
    private Integer boundResumeCount;
    private LocalDateTime createdAt;

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getWechatId() {
        return wechatId;
    }

    public void setWechatId(String wechatId) {
        this.wechatId = wechatId;
    }

    public String getAvatarUrl() {
        return avatarUrl;
    }

    public void setAvatarUrl(String avatarUrl) {
        this.avatarUrl = avatarUrl;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public Integer getBoundResumeCount() {
        return boundResumeCount;
    }

    public void setBoundResumeCount(Integer boundResumeCount) {
        this.boundResumeCount = boundResumeCount;
    }

    public LocalDateTime getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(LocalDateTime createdAt) {
        this.createdAt = createdAt;
    }
}
